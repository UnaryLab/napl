"""
Generate golden test vectors for the eq RTL module straight from napl's
functional Python model (napl.sim.operation.eq) -- so the testbench checks the
Verilog against the *actual* simulator, not a hand-derived truth table.

eq is stateful: it holds one unsigned WIDTH-bit saturating counter reset to
HALF = 2**(WIDTH-1). A 10 input pair counts up, 01 counts down, and 00 and 11
hold; the per-timestep output is combinational on the post-update counter,

    y_t = 1{ |cnt_t - HALF| <= TOLERANCE }.

Polarity does not change the circuit, so one module covers both codes and the
two polarities are driven as successive segments of one stream.

Output: ../vec/eq.vec, one line per cycle:

    <rst_n> <in0> <in1> <out>   (each 0/1)

A line with rst_n==0 is a reset pulse: the inputs/outputs are don't-care (0) and
the TB asserts i_rst_n low for that cycle, proving the active-low reset returns
the counter to HALF from a dirtied state (matching reset()).

Also emits ../vec/eq_params.vh with GEN_WIDTH and GEN_TOLERANCE, the single
source of truth the RTL and TB inherit from.

Run inside the `napl` conda env (so `import napl` resolves):
    python gen/gen_eq.py
"""
import sys
from pathlib import Path

import torch
from napl.sim.operation import eq
from napl.syn import translate_node

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from _gen_common import pair_streams, rep_pairs

VECDIR = Path(__file__).resolve().parent.parent / "vec"
VEC = VECDIR / "eq.vec"
HDR = VECDIR / "eq_params.vh"

# Counter sizing, mirroring _WIDTH and _TOLERANCE in tests/operation/test_eq.py.
WIDTH = 3
TOLERANCE = 1
# Encoder timestep and sobol dims mirror the streaming test's codec config.
TIMESTEP = 256


def codecs(polarity):
    c0 = {"polarity": polarity, "timestep": TIMESTEP, "generator": "sobol", "dim": 1}
    c1 = {"polarity": polarity, "timestep": TIMESTEP, "generator": "sobol", "dim": 2}
    return c0, c1


def build_rows(polarity, pairs, seen):
    """Per-cycle (rst_n, in0, in1, out) rows; each pair is its own reset segment.

    Each representative value pair is encoded and run as a fresh TIMESTEP-long
    segment, with the model reset (and a reset-pulse row emitted) between pairs,
    so the co-simulation replays the same inputs after a mid-run reset.

    `seen` collects every counter state the model visits, so the caller can
    require both saturation rails to appear in a compared row.
    """
    model = eq({"polarity": polarity, "width": WIDTH, "tolerance": TOLERANCE})
    c0, c1 = codecs(polarity)
    rows = []
    for pair in pairs:
        model.reset()
        rows.append((0, 0, 0, 0))
        s0, s1 = pair_streams(c0, c1, [pair])
        for a, b in zip(s0, s1):
            out = int(model(torch.tensor(a), torch.tensor(b)).item())
            seen.add(int(model.cnt.item()))
            rows.append((1, a, b, out))
    return rows


def check_mapping():
    """Fail if mapping.yaml's eq params drift from this gen's elaborated values.

    The testbench elaborates one DUT at the WIDTH and TOLERANCE fixed here.
    Resolving the mapping entry for a deployment node carrying the same config
    and requiring it to reproduce those exact params ties the shipped config to
    the co-sim-verified one, so a mapping formula that drifts trips this assert
    during `make test`.
    """
    for polarity in ("unipolar", "bipolar"):
        binding = translate_node({
            "class": "eq",
            "config": {"polarity": polarity, "width": WIDTH, "tolerance": TOLERANCE},
        })
        expected = {"WIDTH": WIDTH, "TOLERANCE": TOLERANCE}
        assert binding.parameters == expected, \
            f"mapping.yaml eq ({polarity}) resolves {binding.parameters}, not {expected}"


def main():
    check_mapping()

    seen = set()
    rows = []
    # Both polarities run through the same circuit, so their segments are
    # concatenated into one stream rather than driving two instances.
    for polarity in ("unipolar", "bipolar"):
        rows += build_rows(polarity, rep_pairs(polarity, polarity), seen)

    # WIDTH is observable only through a saturated counter, so require both
    # rails to be reached by a compared row.
    assert 0 in seen and 2 ** WIDTH - 1 in seen, \
        f"counter states {sorted(seen)} miss a saturation rail of width {WIDTH}"

    VECDIR.mkdir(parents=True, exist_ok=True)
    # The testbench counts only the driven rows, not the reset-pulse rows.
    compared = 0
    with VEC.open("w") as f:
        for rst_n, a, b, out in rows:
            f.write(f"{rst_n} {a} {b} {out}\n")
            if rst_n:
                compared += 1
    with HDR.open("w") as f:
        f.write("// Generated by gen_eq.py from tests/operation/test_eq.py config.\n")
        f.write(f"`define GEN_WIDTH {WIDTH}\n")
        f.write(f"`define GEN_TOLERANCE {TOLERANCE}\n")
        f.write(f"`define GEN_VECTORS {compared}\n")
    print(f"wrote {VEC} ({len(rows)} vectors); {HDR} "
          f"(WIDTH={WIDTH} TOLERANCE={TOLERANCE}); counter states {sorted(seen)}")


if __name__ == "__main__":
    main()
